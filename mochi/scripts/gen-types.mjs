#!/usr/bin/env node
// 由 shared/schema/protocol.schema.json 生成前端 TS 类型（T0-05）。
// 用法：node scripts/gen-types.mjs
// 纪律：生成物禁止手改；CI 中执行后校验 git diff（不变量 I4）。

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const schemaPath = resolve(root, 'shared/schema/protocol.schema.json');
const outPath = resolve(root, 'frontend/src/types/protocol.ts');

const bundle = JSON.parse(readFileSync(schemaPath, 'utf8'));
const defs = bundle.$defs ?? {};

function tsType(schema, indent = 0) {
  if (!schema || typeof schema !== 'object') return 'unknown';
  if (schema.$ref) return schema.$ref.split('/').pop();
  if (schema.const !== undefined) return JSON.stringify(schema.const);
  if (Array.isArray(schema.anyOf)) return schema.anyOf.map((s) => tsType(s, indent)).join(' | ');
  if (Array.isArray(schema.enum)) return schema.enum.map((v) => JSON.stringify(v)).join(' | ');
  switch (schema.type) {
    case 'string':
      return 'string';
    case 'integer':
    case 'number':
      return 'number';
    case 'boolean':
      return 'boolean';
    case 'null':
      return 'null';
    case 'array':
      return `${tsType(schema.items, indent)}[]`;
    case 'object': {
      const props = schema.properties ?? {};
      if (Object.keys(props).length === 0 && schema.additionalProperties) {
        const value =
          schema.additionalProperties === true
            ? 'unknown'
            : tsType(schema.additionalProperties, indent);
        return `Record<string, ${value}>`;
      }
      const required = new Set(schema.required ?? []);
      const pad = ' '.repeat(indent + 2);
      const lines = Object.entries(props).map(([key, value]) => {
        const safeKey = /^[A-Za-z_$][\w$]*$/.test(key) ? key : JSON.stringify(key);
        return `${pad}${safeKey}${required.has(key) ? '' : '?'}: ${tsType(value, indent + 2)};`;
      });
      return `{\n${lines.join('\n')}\n${' '.repeat(indent)}}`;
    }
    default:
      return 'unknown';
  }
}

const header = [
  '// AUTO-GENERATED by scripts/gen-types.mjs — DO NOT EDIT.',
  '// Source: shared/schema/protocol.schema.json',
  '',
  `export const PROTOCOL_VERSION = ${bundle.protocolVersion ?? 1};`,
  '',
];

const body = [];
for (const [name, schema] of Object.entries(defs).sort(([a], [b]) => a.localeCompare(b))) {
  if (!schema || typeof schema !== 'object') continue;
  if (Array.isArray(schema.enum) && schema.type === 'string') {
    body.push(`export type ${name} = ${schema.enum.map((v) => JSON.stringify(v)).join(' | ')};`, '');
    continue;
  }
  if (schema.type === 'object' && schema.properties) {
    body.push(`export interface ${name} ${tsType(schema)}`, '');
    continue;
  }
  body.push(`export type ${name} = ${tsType(schema)};`, '');
}

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, [...header, ...body].join('\n'), 'utf8');
console.log(`wrote ${outPath} (${Object.keys(defs).length} defs)`);
